// Writes .env.localdb (frontend) and server/.env.localdb (server) pointing at
// the local Supabase stack. When this Mac is signed in to Tailscale the app
// uses its Tailscale name (flowtone-mac.<tailnet>.ts.net), which the iPhone
// reaches from anywhere with Tailscale on; iOS only allows plain http to it
// because Info.plist exempts ts.net (a bare 100.x address is blocked).
// Otherwise the LAN IP, which only works on the same Wi-Fi. `--lan` forces
// the LAN IP. Re-run when the address changes. Keys come from
// `supabase status`; both files are gitignored.
import { execSync, execFileSync } from 'child_process';
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { networkInterfaces, homedir } from 'os';

// tailscaled runs as a user service with its own socket (no admin rights
// needed); the default socket covers the Tailscale Mac app.
function tailscaleName() {
  for (const socket of [[`--socket=${homedir()}/.tailscale/tailscaled.sock`], []]) {
    try {
      const status = JSON.parse(execFileSync('tailscale', [...socket, 'status', '--json'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }));
      const name = status.BackendState === 'Running' && status.Self?.DNSName?.replace(/\.$/, '');
      if (name?.endsWith('.ts.net')) return name;
    } catch { /* not installed or not signed in */ }
  }
  return null;
}

const lanIp = Object.values(networkInterfaces())
  .flat()
  .find((i) => i && i.family === 'IPv4' && !i.internal)?.address;
const tsName = process.argv.includes('--lan') ? null : tailscaleName();
const host = tsName || lanIp;
if (!host) throw new Error('No LAN IPv4 address found - is Wi-Fi on?');

const status = JSON.parse(execSync('supabase status -o json', { encoding: 'utf8' }));
const supabaseUrl = `http://${host}:54321`;
const apiUrl = `http://${host}:3001`;

writeFileSync('.env.localdb', [
  '# Generated by scripts/write-local-env.mjs - local Supabase on this Mac',
  `VITE_SUPABASE_URL=${supabaseUrl}`,
  `VITE_SUPABASE_ANON_KEY=${status.ANON_KEY}`,
  `VITE_API_URL=${apiUrl}`,
  '',
].join('\n'));

// Server: keep everything from server/.env (Anthropic, VAPID, ...) and only
// swap the database it talks to.
const base = existsSync('server/.env') ? readFileSync('server/.env', 'utf8') : '';
const kept = base.split('\n').filter((l) => !/^(SUPABASE_URL|SUPABASE_SERVICE_ROLE_KEY)=/.test(l.trim()));
// MAIL_SECRET_KEY encrypts stored iCloud Mail passwords: losing it means every
// mailbox must be reconnected, so carry it over when server/.env has none.
if (!kept.some((l) => /^MAIL_SECRET_KEY=/.test(l.trim())) && existsSync('server/.env.localdb')) {
  const previous = readFileSync('server/.env.localdb', 'utf8').split('\n').find((l) => /^MAIL_SECRET_KEY=/.test(l.trim()));
  if (previous) kept.push(previous.trim());
}
writeFileSync('server/.env.localdb', [
  '# Generated by scripts/write-local-env.mjs - local Supabase on this Mac',
  ...kept.filter((l) => l.trim()),
  `SUPABASE_URL=http://127.0.0.1:54321`,
  `SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}`,
  '',
].join('\n'));

console.log(`Local env written (${tsName ? 'Tailscale, works anywhere' : 'LAN, home Wi-Fi only'}). Database: ${supabaseUrl}  API: ${apiUrl}`);
